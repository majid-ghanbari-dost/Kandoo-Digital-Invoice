"""Stable verdict and reason-code strings returned by E-06."""
from __future__ import annotations

from enum import Enum


class Verdict(str, Enum):
    ACCEPT = "ACCEPT"
    REVIEW = "REVIEW"
    REJECT = "REJECT"


class ReasonCode(str, Enum):
    # Positive/pass evidence; conditional gates appear only when applicable.
    TEMPLATE_MATCH_HIGH = "TEMPLATE_MATCH_HIGH"
    STRUCTURE_VALID = "STRUCTURE_VALID"
    NUMS_CONSISTENT = "NUMS_CONSISTENT"
    EXTRACTION_CONFIDENCE_HIGH = "EXTRACTION_CONFIDENCE_HIGH"
    LAYOUT_SIMILARITY_HIGH = "LAYOUT_SIMILARITY_HIGH"
    DIGIT_COVERAGE_VALID = "DIGIT_COVERAGE_VALID"
    ONBOARDING_COMPLETE = "ONBOARDING_COMPLETE"
    TEMPLATE_BANK_LOCKED = "TEMPLATE_BANK_LOCKED"
    D14_AGREEMENT_SIGNED = "D14_AGREEMENT_SIGNED"
    OWNER_VERIFICATION_AUDITED = "OWNER_VERIFICATION_AUDITED"

    # Non-terminal review conditions.
    LOW_CONFIDENCE = "LOW_CONFIDENCE"
    ACCOUNTING_ADJUSTMENT_UNSUPPORTED = "ACCOUNTING_ADJUSTMENT_UNSUPPORTED"
    CURRENCY_UNIT_UNCONFIRMED = "CURRENCY_UNIT_UNCONFIRMED"
    PARTIAL_MATCH = "PARTIAL_MATCH"
    NEW_LAYOUT = "NEW_LAYOUT"
    MULTI_TEMPLATE_AMBIGUOUS = "MULTI_TEMPLATE_AMBIGUOUS"
    SELF_MATCH_RESUBSTITUTION = "SELF_MATCH_RESUBSTITUTION"
    ONBOARDING_WARMUP = "ONBOARDING_WARMUP"
    TEMPLATE_BANK_UNLOCKED = "TEMPLATE_BANK_UNLOCKED"
    D14_AGREEMENT_REQUIRED = "D14_AGREEMENT_REQUIRED"
    DIGIT_COVERAGE_INSUFFICIENT = "DIGIT_COVERAGE_INSUFFICIENT"
    ATTENTION_REQUIRED = "ATTENTION_REQUIRED"
    CANONICAL_STATE_NOT_READY = "CANONICAL_STATE_NOT_READY"
    OWNER_VERIFICATION_REQUIRED = "OWNER_VERIFICATION_REQUIRED"
    MANUAL_OVERRIDE_BLOCKED = "MANUAL_OVERRIDE_BLOCKED"
    MANUAL_OVERRIDE_INVALID = "MANUAL_OVERRIDE_INVALID"
    MANUAL_OVERRIDE_APPLIED = "MANUAL_OVERRIDE_APPLIED"

    # Hard failures, including an explicit audited owner rejection.
    MANUAL_OWNER_REJECTED = "MANUAL_OWNER_REJECTED"
    SCHEMA_INVALID = "SCHEMA_INVALID"
    NUMS_INCONSISTENT = "NUMS_INCONSISTENT"
    NO_MATCH = "NO_MATCH"
