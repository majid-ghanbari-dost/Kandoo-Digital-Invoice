#!/usr/bin/env python3
"""Verify the E-03 v3 Holo entry kit and regenerate its glyph-coverage table.

Checks the 3-learning/1-exam page set, exact numeric ground truth, Persian
controlled-value coverage, and quantity × entry-only unit-price arithmetic.
This does not print invoices, connect to Holo, capture a Windows spool job, or
certify KandooPrintProbe output provenance.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
KIT_DIR = REPO_ROOT / "docs" / "E-03-kit-v3"
PAGE_FILES = {
    "learning-1": "learning-1.md",
    "learning-2": "learning-2.md",
    "learning-3": "learning-3.md",
    "exam": "exam.md",
}
PERSIAN_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
REQUIRED_GLYPHS = PERSIAN_DIGITS + ","
MIN_GLYPH_COUNT = 5
PERSIAN_TO_ASCII = str.maketrans(PERSIAN_DIGITS, "0123456789")
QUANTITY_RE = re.compile(r"^[۰-۹]+$")
AMOUNT_RE = re.compile(r"^[۰-۹]{1,3}(?:,[۰-۹]{3})+$")
PERSIAN_LETTER_RE = re.compile(r"[\u0600-\u06ff]")
MATRIX_ROW_RE = re.compile(r"^\|\s*(?:\d+|comma)\s*\|\s*`([۰-۹,])`\s*\|\s*(\d+)\s*\|")
COVERAGE_START = "<!-- E03-V3-COVERAGE-START -->"
COVERAGE_END = "<!-- E03-V3-COVERAGE-END -->"
GENERATOR_NOTE = "<!-- Generated by scripts/verify_e03_kit_v3.py --write-coverage; do not hand-edit counts. -->"


class KitValidationError(ValueError):
    """Raised when a kit page, answer key, arithmetic check, or matrix is invalid."""


def _fail(message: str) -> None:
    raise KitValidationError(message)


def _parse_quantity(value: Any, where: str) -> int:
    if not isinstance(value, str) or not QUANTITY_RE.fullmatch(value):
        _fail(f"{where} must be a whole Persian-digit quantity without separators")
    parsed = int(value.translate(PERSIAN_TO_ASCII))
    if parsed <= 0:
        _fail(f"{where} must be greater than zero")
    return parsed


def _parse_amount(value: Any, where: str) -> int:
    if not isinstance(value, str) or not AMOUNT_RE.fullmatch(value):
        _fail(f"{where} must use Persian digits and comma-separated thousands")
    return int(value.translate(PERSIAN_TO_ASCII).replace(",", ""))


def _page_values_from_markdown(path: Path) -> dict[str, Any]:
    item_names: list[str] = []
    quantities: list[str] = []
    line_totals: list[str] = []
    unit_prices: list[str] = []
    payable: str | None = None

    for source_line in path.read_text(encoding="utf-8").splitlines():
        line = source_line.strip()
        if not line.startswith("|"):
            continue
        cells = [cell.strip().strip("*").strip() for cell in line.strip("|").split("|")]
        if len(cells) != 4:
            continue
        label = cells[0]
        if label.casefold().startswith("payable") or label.startswith("قابل پرداخت"):
            if cells[2] == "—":
                _fail(f"{path.name}: payable row has no numeric amount")
            payable = cells[2]
            if cells[3] != "—":
                _fail(f"{path.name}: payable row must not contain an entry-only unit price")
        elif QUANTITY_RE.fullmatch(cells[1]):
            if not PERSIAN_LETTER_RE.search(label):
                _fail(f"{path.name}: item names must be real Persian names, not generic placeholders")
            if label.casefold() in {"item a", "item b", "item c", "item d"}:
                _fail(f"{path.name}: generic Item A/B/C/D labels are not permitted")
            item_names.append(label)
            quantities.append(cells[1])
            line_totals.append(cells[2])
            unit_prices.append(cells[3])

    if len(quantities) != 4 or payable is None:
        _fail(f"{path.name}: expected exactly four Persian-named item rows and one payable row")
    return {
        "item_names": item_names,
        "quantities": quantities,
        "line_totals": line_totals,
        "unit_prices": unit_prices,
        "payable": payable,
    }


def _controlled_values(page: dict[str, Any]) -> list[str]:
    return [*page["quantities"], *page["line_totals"], page["payable"]]


def _coverage_from_values(data: dict[str, Any]) -> tuple[Counter[str], dict[str, Counter[str]]]:
    counts: Counter[str] = Counter()
    page_counts: dict[str, Counter[str]] = {}
    for page_id, page in data.items():
        current = Counter(glyph for value in _controlled_values(page) for glyph in value)
        page_counts[page_id] = current
        counts.update(current)
        if current["۲"] < MIN_GLYPH_COUNT or current["۶"] < MIN_GLYPH_COUNT:
            _fail(
                f"{page_id}: keep at least five each of look-alike Persian ۲ and ۶ on every page"
            )
        if not any(pair in "".join(_controlled_values(page)) for pair in ("۲۶", "۶۲")):
            _fail(f"{page_id}: include adjacent look-alike digits ۲۶ or ۶۲ in controlled values")
    return counts, page_counts


def _coverage_markdown(counts: Counter[str]) -> str:
    lines = [
        "| Symbol | Printed glyph | Count | Minimum 5? |",
        "|---:|:---:|---:|:---:|",
    ]
    for digit, glyph in enumerate(PERSIAN_DIGITS):
        lines.append(f"| {digit} | `{glyph}` | {counts[glyph]} | {'Yes' if counts[glyph] >= MIN_GLYPH_COUNT else 'No'} |")
    lines.append(f"| comma | `,` | {counts[',']} | {'Yes' if counts[','] >= MIN_GLYPH_COUNT else 'No'} |")
    return "\n".join(lines)


def _write_coverage_matrix(readme_path: Path, counts: Counter[str]) -> None:
    readme = readme_path.read_text(encoding="utf-8")
    if readme.count(COVERAGE_START) != 1 or readme.count(COVERAGE_END) != 1:
        _fail("README must contain exactly one generated-coverage marker pair")
    start = readme.index(COVERAGE_START) + len(COVERAGE_START)
    end = readme.index(COVERAGE_END)
    if end <= start:
        _fail("README coverage markers are out of order")
    replacement = f"\n{GENERATOR_NOTE}\n{_coverage_markdown(counts)}\n"
    readme_path.write_text(readme[:start] + replacement + readme[end:], encoding="utf-8")


def _read_matrix(readme_path: Path) -> dict[str, int]:
    text = readme_path.read_text(encoding="utf-8")
    if text.count(COVERAGE_START) != 1 or text.count(COVERAGE_END) != 1:
        _fail("README must contain exactly one generated-coverage marker pair")
    start = text.index(COVERAGE_START) + len(COVERAGE_START)
    end = text.index(COVERAGE_END)
    if end <= start:
        _fail("README coverage markers are out of order")
    matrix: dict[str, int] = {}
    for line in text[start:end].splitlines():
        match = MATRIX_ROW_RE.match(line.strip())
        if match:
            glyph, count = match.groups()
            if glyph in matrix:
                _fail(f"README coverage matrix repeats glyph {glyph!r}")
            matrix[glyph] = int(count)
    if set(matrix) != set(REQUIRED_GLYPHS):
        _fail("generated README coverage matrix must contain exactly digits ۰–۹ and comma")
    return matrix


def verify_kit(kit_dir: Path = KIT_DIR, *, write_coverage: bool = False) -> dict[str, int]:
    """Validate every page/row and return glyph counts; optionally regenerate README matrix."""
    expected_files = {"README.md", "expected-values.json", *PAGE_FILES.values()}
    if not kit_dir.is_dir():
        _fail(f"kit directory does not exist: {kit_dir}")
    actual_files = {path.name for path in kit_dir.iterdir() if path.is_file()}
    markdown_pages = {name for name in actual_files if name.endswith(".md") and name != "README.md"}
    if markdown_pages != set(PAGE_FILES.values()):
        _fail(
            "kit must contain exactly three learning page files and one exam page file; "
            f"found {sorted(markdown_pages)}"
        )
    missing = expected_files - actual_files
    if missing:
        _fail(f"kit is missing required files: {sorted(missing)}")

    readme_path = kit_dir / "README.md"
    page_docs = [readme_path.read_text(encoding="utf-8")]
    page_docs.extend((kit_dir / filename).read_text(encoding="utf-8") for filename in PAGE_FILES.values())
    joined_docs = "\n".join(page_docs)
    if "Holo" not in joined_docs or "هلو" not in joined_docs:
        _fail("v3 docs must identify Holo using Holo («هلو»)")
    for phrase in ("No real customer", "sale", "stock movement", "discarded"):
        if phrase.casefold() not in joined_docs.casefold():
            _fail(f"README is missing required safety wording: {phrase}")

    try:
        data = json.loads((kit_dir / "expected-values.json").read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _fail(f"expected-values.json is invalid JSON: {exc}")
    if not isinstance(data, dict) or set(data) != set(PAGE_FILES):
        _fail(f"expected-values.json must contain exactly these page keys: {list(PAGE_FILES)}")

    arithmetic_rows = 0
    learning_large_page_found = False
    for page_id, filename in PAGE_FILES.items():
        page = data[page_id]
        if not isinstance(page, dict) or set(page) != {"quantities", "line_totals", "payable"}:
            _fail(
                f"{page_id}: ground truth fields must be only quantities, line_totals, and payable"
            )
        quantities = page["quantities"]
        line_totals = page["line_totals"]
        if not isinstance(quantities, list) or not isinstance(line_totals, list):
            _fail(f"{page_id}: quantities and line_totals must be arrays")
        if len(quantities) != 4 or len(line_totals) != 4:
            _fail(f"{page_id}: each page must have exactly four quantity/line-total pairs")

        numeric_rows = _page_values_from_markdown(kit_dir / filename)
        rendered_ground_truth = {
            "quantities": numeric_rows["quantities"],
            "line_totals": numeric_rows["line_totals"],
            "payable": numeric_rows["payable"],
        }
        if rendered_ground_truth != page:
            _fail(f"{filename}: printed target values do not match expected-values.json")

        quantity_values = [
            _parse_quantity(value, f"{page_id}.quantities[{index}]")
            for index, value in enumerate(quantities)
        ]
        total_values = [
            _parse_amount(value, f"{page_id}.line_totals[{index}]")
            for index, value in enumerate(line_totals)
        ]
        price_values = [
            _parse_amount(value, f"{page_id}.entry_only_unit_prices[{index}]")
            for index, value in enumerate(numeric_rows["unit_prices"])
        ]
        payable_value = _parse_amount(page["payable"], f"{page_id}.payable")
        if any(value <= 0 for value in (*total_values, *price_values, payable_value)):
            _fail(f"{page_id}: line totals, entry-only unit prices, and payable must be positive")
        if sum(total_values) != payable_value:
            _fail(f"{page_id}: payable does not equal the sum of line totals")
        for index, (quantity, price, total) in enumerate(
            zip(quantity_values, price_values, total_values, strict=True)
        ):
            if total % quantity != 0 or quantity * price != total:
                _fail(
                    f"{filename} row {index + 1}: quantity {quantity} × entry-only unit price "
                    f"{price} != target line total {total}"
                )
            arithmetic_rows += 1

        if page_id.startswith("learning-") and all(
            10_000_000 <= total <= 999_999_999 for total in total_values
        ) and 1_000_000 <= payable_value <= 999_999_999:
            learning_large_page_found = True

    if not learning_large_page_found:
        _fail("at least one learning page must include an 8–9 digit line total and 7–9 digit payable")

    counts, page_counts = _coverage_from_values(data)
    missing_glyphs = {
        glyph: counts[glyph]
        for glyph in REQUIRED_GLYPHS
        if counts[glyph] < MIN_GLYPH_COUNT
    }
    if missing_glyphs:
        _fail(f"combined controlled-value glyph coverage is below five: {missing_glyphs}")

    if write_coverage:
        _write_coverage_matrix(readme_path, counts)
    matrix = _read_matrix(readme_path)
    actual_counts = {glyph: counts[glyph] for glyph in REQUIRED_GLYPHS}
    if matrix != actual_counts:
        _fail(f"README coverage matrix is stale: {matrix} != {actual_counts}")

    # Kept separate from the return value so CLI output can certify all 16 products.
    verify_kit.last_arithmetic_rows = arithmetic_rows  # type: ignore[attr-defined]
    verify_kit.last_page_counts = page_counts  # type: ignore[attr-defined]
    return actual_counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kit-dir", type=Path, default=KIT_DIR, help="kit directory to verify")
    parser.add_argument(
        "--write-coverage",
        action="store_true",
        help="regenerate the README matrix from expected-values.json before verifying it",
    )
    args = parser.parse_args(argv)

    try:
        counts = verify_kit(args.kit_dir, write_coverage=args.write_coverage)
        arithmetic_rows = getattr(verify_kit, "last_arithmetic_rows", 0)
        page_counts = getattr(verify_kit, "last_page_counts", {})
        print("E-03-kit-v3 pages, ground truth, payable sums, and coverage matrix: PASS")
        print(f"Quantity × entry-only unit price = line total: {arithmetic_rows}/16 rows PASS")
        for page_id in PAGE_FILES:
            print(
                f"{page_id}: look-alike ۲={page_counts[page_id]['۲']}, "
                f"۶={page_counts[page_id]['۶']} (minimum five each; adjacent ۲۶/۶۲ present)"
            )
        print("Symbol | Printed glyph | Combined count | Result")
        for glyph in REQUIRED_GLYPHS:
            label = "comma" if glyph == "," else str(PERSIAN_DIGITS.index(glyph))
            print(f"{label} | {glyph} | {counts[glyph]} | PASS (minimum {MIN_GLYPH_COUNT})")
        if args.write_coverage:
            print("README coverage matrix: REGENERATED and verified")
    except (OSError, KitValidationError) as exc:
        print(f"E-03-kit-v3 validation failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
